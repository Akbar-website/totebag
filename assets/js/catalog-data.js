window.TOTEBAG_CATALOG_MAP = {};
window.TOTEBAG_CATALOG.forEach(function (p) {
  window.TOTEBAG_CATALOG_MAP[p.id] = p;
  window.TOTEBAG_CATALOG_MAP[p.name.toLowerCase()] = p;
});

window.getProductById = function (id) {
  if (!id) return window.TOTEBAG_CATALOG[0];
  var cleanId = id.toString().trim().toLowerCase();
  if (window.TOTEBAG_CATALOG_MAP[cleanId]) return window.TOTEBAG_CATALOG_MAP[cleanId];
  for (var i = 0; i < window.TOTEBAG_CATALOG.length; i++) {
    var p = window.TOTEBAG_CATALOG[i];
    if (p.id === cleanId || p.id.indexOf(cleanId) !== -1 || cleanId.indexOf(p.id) !== -1) {
      return p;
    }
  }
  return window.TOTEBAG_CATALOG[0];
};

window.getRelatedProducts = function (category, currentId, limit) {
  limit = limit || 4;
  var sameCat = window.TOTEBAG_CATALOG.filter(function (p) {
    return p.category === category && p.id !== currentId;
  });
  if (sameCat.length >= limit) return sameCat.slice(0, limit);
  var others = window.TOTEBAG_CATALOG.filter(function (p) {
    return p.category !== category && p.id !== currentId;
  });
  return sameCat.concat(others.slice(0, limit - sameCat.length));
};
